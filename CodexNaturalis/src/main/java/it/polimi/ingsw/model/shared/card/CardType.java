package it.polimi.ingsw.model.shared.card;

/**
* Represents the four possible type of cards in the game.
 *
 * @author Andrea Fidanza, Marco Maiocchi, Francesco Nisoli, Guglielmo Gatti
*/
public enum CardType {

    /**
     * the resource cards' type.
     */
    RESOURCE,
    /**
     * the gold cards' type.
     */
    GOLD,
    /**
     * the starter cards' type.
     */
    STARTER,
    /**
     * the objective cards' type.
     */
    OBJECTIVE
}